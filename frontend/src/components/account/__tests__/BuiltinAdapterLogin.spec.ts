    await vi.advanceTimersByTimeAsync(2500)
    await flushPromises()
    expect(complete).toHaveBeenLastCalledWith('teleagent', session, '', expect.any(AbortSignal), scope)
    expect(wrapper.emitted('authorized')).toEqual([[completed]])
