    const completed = { ...session, status: 'completed', api_key: `ta-${'c'.repeat(64)}`, account: { uid: 'user-1', nickname: 'Test user' } }
    start.mockResolvedValue(session)
    complete.mockResolvedValueOnce(session).mockResolvedValueOnce(completed)
    const wrapper = mount(BuiltinAdapterLogin, { props: { platform: 'teleagent', scope }, attachTo: document.body })
    expect(wrapper.get('button').text()).toBe('admin.accounts.builtinLogin.teleagentStart')
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(start).toHaveBeenCalledWith('teleagent', expect.any(AbortSignal), undefined, scope)
    expect(wrapper.find('a').exists()).toBe(false)
    expect(getView).toHaveBeenCalledWith('teleagent', 'abc', expect.any(AbortSignal), scope)
    const img = wrapper.get('[data-testid="teleagent-login-view"]')
    expect(img.attributes('src')).toBe('blob:teleagent-login')
    expect(img.attributes('alt')).toBe('admin.accounts.builtinLogin.teleagentViewAlt')
    Object.defineProperty(img.element, 'naturalWidth', { configurable: true, value: 720 })
    Object.defineProperty(img.element, 'naturalHeight', { configurable: true, value: 760 })
    Object.defineProperty(img.element, 'getBoundingClientRect', { configurable: true, value: () => ({ left: 20, top: 10, width: 360, height: 380 }) })
    const surface = wrapper.get('[data-testid="builtin-login-view-surface"]')
    await surface.trigger('click', { clientX: 200, clientY: 200 })
    await flushPromises()
    expect(sendInput).toHaveBeenLastCalledWith('teleagent', 'abc', { type: 'click', x: 360, y: 380 }, undefined, scope)
    const input = wrapper.get('[data-testid="builtin-login-input"]')
    expect(document.activeElement).toBe(input.element)
    await input.setValue('13800001111')
    await flushPromises()
    expect(sendInput).toHaveBeenLastCalledWith('teleagent', 'abc', { type: 'text', text: '13800001111' }, undefined, scope)
    await surface.trigger('keydown', { key: 'Enter' })
    await flushPromises()
    expect(sendInput).toHaveBeenLastCalledWith('teleagent', 'abc', { type: 'key', key: 'Enter' }, undefined, scope)
