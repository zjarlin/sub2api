    expect(wrapper.find('[data-testid="deepseek-auto-relogin-status"]').exists()).toBe(false)
    await wrapper.get('#deepseek-login-email').setValue('user@example.com')
    await wrapper.get('#deepseek-login-password').setValue('password')
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(start).toHaveBeenCalledWith('deepseek_web', expect.any(AbortSignal), { email: 'user@example.com', password: 'password', auto_relogin: true }, 'admin')
    expect((wrapper.get('#deepseek-login-password').element as HTMLInputElement).value).toBe('')
    expect(wrapper.get('#deepseek-auto-relogin').attributes('disabled')).toBeDefined()
    expect(wrapper.get('#deepseek-login-email').attributes('disabled')).toBeDefined()
    expect(wrapper.get('#deepseek-login-password').attributes('disabled')).toBeDefined()
    expect(wrapper.text()).toContain('admin.accounts.builtinLogin.deepseekWebHint')
    expect(wrapper.text()).not.toContain('admin.accounts.builtinLogin.deepseek_webHint')
